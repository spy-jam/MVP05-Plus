#!/usr/bin/env python3
"""gc.json (from gc_extract.py) -> src/game/gc_layout_table.h and a readable comparison sheet.

GameCube pad channels, from the gcpad poll fn_8000A44C (PADStatus into m4[]):
  1 Right 2 Left 3 Down 4 Up 5 Z 6 A 7 B 8 X 9 Y 10 Start 11 L (analog) 12 R (analog)
  13/14 stick x+/x- 15/16 stick y+/y- 17/18 C x+/x- 19/20 C y+/y-   (the L/R digital clicks are never read)
Xbox pad channels, from the pad poll 0x2BF350:
  1 Up 2 Down 3 Left 4 Right 5 Start 6 Back 7 LThumb 8 RThumb 9 A 10 B 11 X 12 Y 13 Black 14 White
  15 LT 16 RT 17/18 LX+/- 19/20 LY+/- 21/22 RX+/- 23/24 RY+/-
gc_controls.cpp puts each GameCube button on the Xbox channel below, so the alias entries (0xED..0x104, virtual
button n -> channel) are translated through it; the action entries refer to virtual buttons and stay as they are.
usage: gen_table.py gc.json xbox_tables.json out_header out_sheet
"""
import json, struct, sys

GC_TO_XBOX = {1: 4, 2: 3, 3: 2, 4: 1, 5: 14, 6: 9, 7: 10, 8: 11, 9: 12, 10: 5, 11: 15, 12: 16,
              13: 17, 14: 18, 15: 19, 16: 20, 17: 21, 18: 22, 19: 23, 20: 24}
# names shared where both pads have the same control (L stick = control stick, R stick = C stick, LT/RT = L/R)
GC_CH = {1: 'D-Right', 2: 'D-Left', 3: 'D-Down', 4: 'D-Up', 5: 'Z', 6: 'A', 7: 'B', 8: 'X', 9: 'Y', 10: 'Start',
         11: 'L/LT', 12: 'R/RT', 13: 'Stick right', 14: 'Stick left', 15: 'Stick up', 16: 'Stick down',
         17: 'C right', 18: 'C left', 19: 'C up', 20: 'C down'}
XB_CH = {1: 'D-Up', 2: 'D-Down', 3: 'D-Left', 4: 'D-Right', 5: 'Start', 6: 'Back', 7: 'LS click', 8: 'RS click',
         9: 'A', 10: 'B', 11: 'X', 12: 'Y', 13: 'Black', 14: 'White', 15: 'L/LT', 16: 'R/RT', 17: 'Stick right',
         18: 'Stick left', 19: 'Stick up', 20: 'Stick down', 21: 'C right', 22: 'C left',
         23: 'C up', 24: 'C down'}
# read modes (fn_802DBDAC: 0-4 read the per-channel edge records at +0x10BC, 5 the analog value); 0/1/2/4 named from use
MODES = {0: 'press', 1: 'release', 2: 'hold', 3: 'mode3', 4: 'repeat', 5: 'analog'}
OPS = {-1: '', 0: '{a} or {b}', 1: '{a} + {b}', 2: '{a} (without {b})', 3: '{a} minus {b}', 4: 'while {a}: {b}', 5: 'unless {a}: {b}'}
N = 0x10A  # entries the defaults write (0x10A is never set by either release)
# Where the Xbox code reads an action the GameCube code doesn't, the GameCube button that does that job there.
OVERRIDES = {}

def load():
    g = json.load(open(sys.argv[1])); x = json.load(open(sys.argv[2]))
    gc = {}
    for k, v in g['defaults']['table'].items(): gc[int(k)] = (v['shorts'][:5], v['scale'])
    for k, v in g['gc_layout']['table'].items(): gc[int(k)] = (v['shorts'][:5], v['scale'])
    xb = {}
    for k, v in x['defaults'].items(): xb[int(k)] = (v[0], 1.0)
    for k, v in x['xbox'].items(): xb[int(k)] = (v[0], v[1])
    return gc, xb

def alias(table, ch):
    return {i - 0xEC: ch.get(table[i][0][0], 'nothing') for i in range(0xED, 0x105)}

def describe(e, names):
    (a, b, ma, mb, op), sc = e
    def one(v, m):
        if v == -2: return 'unbound'
        if v == -1: return 'nothing'
        if v > 24: return 'action 0x%X' % v
        return '%s [%s]' % (names.get(v, 'nothing'), MODES.get(m, m))
    if a == -2: return 'unbound'
    if op == -1: return one(a, ma)
    return OPS[op].format(a=one(a, ma), b=one(b, mb))

def main():
    gc, xb = load()
    out = []
    for i in range(N):
        (a, b, ma, mb, op), sc = OVERRIDES.get(i, gc[i])
        if 0xED <= i <= 0x104 and a > 0: a = GC_TO_XBOX[a]
        if abs(sc) > 1e6: sc = 1.0  # never written: the constructor's 1.0 (both releases)
        out.append((a, b, ma, mb, op, sc))
    with open(sys.argv[3], 'w') as f:
        f.write('// The GameCube release\'s action table: generated by tools/gc_layout/gen_table.py from the GameCube\n'
                '// main.dol (the shared defaults fn_802D8B64, then the gcpad layout fn_80008664). Virtual-button\n'
                '// aliases (0xED..0x104) are translated to the Xbox channels gc_controls.cpp puts each GameCube button on.\n'
                '// gen_table.py OVERRIDES: actions only the Xbox code reads, bound to the GameCube button for that job.\n'
                '#pragma once\n#include <cstdint>\n\nnamespace gc {\nstruct Entry {\n    int16_t a, b, mode_a, mode_b, op;\n    float scale;\n};\n'
                'constexpr bool kHaveGcTable = true;\nconstexpr uint32_t kGcEntries = 0x%X;\nconstexpr Entry kGcTable[kGcEntries] = {\n' % N)
        for i, e in enumerate(out):
            f.write('    {%d, %d, %d, %d, %d, %sf},  // 0x%03X\n' % (*e[:5], repr(float(e[5])), i))
        f.write('};\n}  // namespace gc\n')
    gcn, xbn = alias(gc, GC_CH), alias(xb, XB_CH)
    lines = ['MVP Baseball 2005: every action the GameCube release binds differently from the Xbox release',
             'Each action names virtual buttons; each release maps those to its own physical buttons.', '',
             'Stick = Xbox left stick / GameCube control stick; C = Xbox right stick / GameCube C stick.',
             'Modes: press, release, hold, repeat (menu auto-repeat), analog. "nothing" never fires.', '',
             'Virtual button   Xbox            GameCube']
    for v in range(1, 25): lines.append('  v%-2d            %-15s %s' % (v, xbn[v], gcn[v]))
    lines += ['', 'Action  Xbox                                           GameCube']
    for i in range(0xED):
        dx, dg = describe(xb[i], xbn), describe(gc[i], gcn)
        if dx != dg: lines.append('0x%03X   %-46s %s' % (i, dx, dg))
    open(sys.argv[4], 'w').write('\n'.join(lines) + '\n')
    print('\n'.join(lines))

main()
